//! Offscreen recorder for the README demos.
//!
//! Runs the real `Rpf9App` inside an `egui_kittest` harness with a wgpu renderer, so no window
//! opens, nothing takes focus and no sound plays. Scripted scenes drive the UI with real pointer
//! and keyboard events, and every frame is piped as raw RGBA into ffmpeg, which writes a
//! near-lossless master `.mp4`. `scripts/readme_media.sh` turns the masters into `assets/`.
//!
//! The demos only show a made-up sample set: models, textures and text generated by
//! `scripts/demo_data.py`, listed under fictional archive names. No game files are opened.
//! Selecting a row hands the matching sample straight to the preview panel, because the
//! samples aren't packed into real archives.
//!
//!   uv run scripts/demo_data.py /tmp/percy6stars-demo-data
//!   SIXSTARS_DEMO_DATA=/tmp/percy6stars-demo-data SIXSTARS_DEMO_OUT=/tmp/percy6stars-demos \
//!     cargo test --release demo_capture -- --ignored --nocapture
//!
//! `SIXSTARS_DEMO_SCENES=overview,models,media,still,scout` picks scenes (default: the three clips).
//! HOME is pointed at an empty folder under the output dir, so the real app data is never read
//! or written.

use crate::*;
use egui_kittest::kittest::{Queryable, by};
use egui_kittest::Harness;
use model3d::Texture2D;
use std::io::Write as _;
use std::process::{Child, ChildStdin, Command, Stdio};
use tex::DecodedTexture;

const W: f32 = 1360.0;
const H: f32 = 820.0;
const PPP: f32 = 2.0;
const FPS: u32 = 30;

/// A sample that a staged row opens in the preview panel.
#[derive(Clone)]
enum Sample {
    Model(&'static str),
    Texture(&'static str),
    Text(&'static str),
}

struct Rec<'a> {
    h: Harness<'a, Rpf9App>,
    ff: Option<(Child, ChildStdin)>,
    cursor: egui::Pos2,
    cursor_img: image::RgbaImage,
    frames: u32,
    data: PathBuf,
    samples: HashMap<usize, Sample>,
    /// extra yaw per frame on top of the viewer's own spin, for livelier turntables
    spin: f32,
}

impl<'a> Rec<'a> {
    fn app(&mut self) -> &mut Rpf9App {
        self.h.state_mut()
    }

    /// Starts piping frames into a new master clip.
    fn begin(&mut self, path: &Path) {
        let (pw, ph) = ((W * PPP) as u32, (H * PPP) as u32);
        let mut child = Command::new("ffmpeg")
            .args(["-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgba", "-s"])
            .arg(format!("{pw}x{ph}"))
            .args(["-r", &FPS.to_string(), "-i", "-", "-c:v", "libx264", "-preset", "medium", "-crf", "8", "-pix_fmt", "yuv444p"])
            .arg(path)
            .stdin(Stdio::piped())
            .spawn()
            .expect("ffmpeg on PATH");
        let stdin = child.stdin.take().unwrap();
        self.ff = Some((child, stdin));
        self.frames = 0;
        eprintln!("recording {}", path.display());
    }

    fn end(&mut self) {
        if let Some((mut child, stdin)) = self.ff.take() {
            drop(stdin);
            child.wait().unwrap();
        }
        eprintln!("  {} frames ({:.1}s)", self.frames, self.frames as f32 / FPS as f32);
    }

    /// Runs one UI frame and records it with the cursor drawn on top.
    fn frame(&mut self) {
        if self.spin != 0.0 {
            let s = self.spin;
            if let Some(m) = self.app().mesh3d.as_mut() {
                m.yaw += s;
                m.dirty = true;
            }
        }
        self.h.step();
        if self.ff.is_none() {
            return;
        }
        let mut img = self.h.render().expect("render");
        draw_cursor(&mut img, &self.cursor_img, self.cursor);
        let (_, stdin) = self.ff.as_mut().unwrap();
        stdin.write_all(img.as_raw()).unwrap();
        self.frames += 1;
    }

    fn hold(&mut self, secs: f32) {
        for _ in 0..(secs * FPS as f32).round() as u32 {
            self.frame();
        }
    }

    /// Glides the cursor to `to` with ease-in-out, sending real pointer moves.
    fn move_to(&mut self, to: egui::Pos2, secs: f32) {
        let from = self.cursor;
        let n = ((secs * FPS as f32).round() as u32).max(1);
        for i in 1..=n {
            let t = i as f32 / n as f32;
            let e = if t < 0.5 { 4.0 * t * t * t } else { 1.0 - (-2.0 * t + 2.0).powi(3) / 2.0 };
            self.cursor = from + (to - from) * e;
            let p = self.cursor;
            self.h.input_mut().events.push(egui::Event::PointerMoved(p));
            self.frame();
        }
    }

    fn button(&mut self, pressed: bool) {
        let p = self.cursor;
        self.h.input_mut().events.push(egui::Event::PointerButton {
            pos: p,
            button: egui::PointerButton::Primary,
            pressed,
            modifiers: Default::default(),
        });
    }

    fn click(&mut self) {
        self.button(true);
        self.frame();
        self.button(false);
        self.frame();
    }

    fn rect_of(&self, label: &str, contains: bool) -> Option<egui::Rect> {
        let node = if contains {
            self.h.query_all(by().label_contains(label)).next()
        } else {
            self.h.query_by_label(label)
        }?;
        node.bounding_box().map(to_points)
    }

    fn find(&self, label: &str) -> egui::Pos2 {
        self.rect_of(label, false).unwrap_or_else(|| panic!("no widget labelled {label:?}")).center()
    }

    /// Clicks a real widget (button, tab, category) by its exact label.
    fn click_label(&mut self, label: &str, secs: f32) {
        let p = self.find(label);
        self.move_to(p, secs);
        self.hold(0.1);
        self.click();
    }

    /// Text field whose rect satisfies `pick` (search boxes are told apart by position).
    fn text_field(&self, pick: impl Fn(egui::Rect) -> bool) -> egui::Pos2 {
        self.h
            .query_all(by().role(egui::accesskit::Role::TextInput))
            .filter_map(|n| n.bounding_box())
            .map(to_points)
            .find(|r| pick(*r))
            .unwrap_or_else(|| {
                let all: Vec<_> = self.h.query_all(by().role(egui::accesskit::Role::TextInput)).filter_map(|n| n.bounding_box()).collect();
                panic!("text field not found among {all:?}")
            })
            .center()
    }

    /// Clicks into a search field, clears it and types `s` a character at a time.
    fn type_into(&mut self, field: egui::Pos2, s: &str, secs: f32) {
        self.move_to(field, secs);
        self.click();
        // clear both search strings (only one field is on screen); select-all via key events
        // doesn't map reliably in the headless harness
        let app = self.app();
        app.filter.clear();
        app.mv_filter.clear();
        self.frame();
        for c in s.chars() {
            let app = self.app();
            if app.tab == AppTab::ModelViewer { app.mv_filter.push(c) } else { app.filter.push(c) }
            self.frame();
            self.frame();
        }
        self.hold(0.25);
    }

    /// Moves to a list row and "clicks" it: the cursor presses, and the sample behind the row
    /// is handed to the preview panel the way a decoded file would be.
    fn open_row(&mut self, name: &str, secs: f32) {
        // long rows are elided in the list, so match on the start of the name
        let key: String = name.chars().take(24).collect();
        let Some(r) = self.rect_of(&key, true) else {
            if let Some(o) = std::env::var_os("SIXSTARS_DEMO_OUT") {
                let _ = self.h.render().unwrap().save(PathBuf::from(o).join("debug_missing_row.png"));
            }
            panic!("no row {name:?} (filter {:?})", self.h.state().filter);
        };
        let p = egui::pos2(r.left() + (r.width() * 0.35).min(160.0), r.center().y);
        self.move_to(p, secs);
        self.hold(0.1);
        let idx = {
            let st = self.app().state.lock().unwrap();
            st.entries.iter().position(|e| e.name == name).unwrap()
        };
        self.stage(idx);
        self.frame();
        self.frame();
    }

    fn stage(&mut self, idx: usize) {
        let sample = self.samples.get(&idx).cloned().expect("row has a sample");
        let name = self.app().state.lock().unwrap().entries[idx].name.clone();
        let data = self.data.clone();
        let app = self.app();
        app.reset_selection();
        app.selected = Some(idx);
        match sample {
            Sample::Model(stem) => {
                let mesh = load_obj_with_atlas(&data, stem, &name);
                app.media.lock().unwrap().loaded_mesh = Some(mesh);
            }
            Sample::Texture(stem) => {
                let t = load_texture(&data.join(format!("{stem}.png")), stem);
                app.media.lock().unwrap().loaded_textures = Some(vec![t]);
            }
            Sample::Text(file) => {
                app.preview = fs::read_to_string(data.join(file)).unwrap();
            }
        }
    }
}

/// AccessKit bounds are in physical pixels; the harness input is in points.
fn to_points(r: egui::accesskit::Rect) -> egui::Rect {
    egui::Rect::from_min_max(
        egui::pos2(r.x0 as f32 / PPP, r.y0 as f32 / PPP),
        egui::pos2(r.x1 as f32 / PPP, r.y1 as f32 / PPP),
    )
}

/// Loads a Z-up `.obj` with `vt` coordinates and its sibling atlas `.png`.
fn load_obj_with_atlas(dir: &Path, stem: &str, name: &str) -> Mesh3D {
    let txt = fs::read_to_string(dir.join(format!("{stem}.obj"))).unwrap();
    let (mut v, mut vt, mut verts, mut uvs, mut tris) = (Vec::new(), Vec::new(), Vec::new(), Vec::new(), Vec::new());
    let mut remap: HashMap<(usize, usize), u32> = HashMap::new();
    for line in txt.lines() {
        let mut it = line.split_whitespace();
        let tag = it.next();
        let nums: Vec<&str> = it.collect();
        match tag {
            Some("v") => v.push([nums[0].parse::<f32>().unwrap(), nums[1].parse().unwrap(), nums[2].parse().unwrap()]),
            Some("vt") => vt.push([nums[0].parse::<f32>().unwrap(), nums[1].parse().unwrap()]),
            Some("f") => {
                let ids: Vec<u32> = nums
                    .iter()
                    .map(|tok| {
                        let mut p = tok.split('/');
                        let vi = p.next().unwrap().parse::<usize>().unwrap() - 1;
                        let ti = p.next().and_then(|s| s.parse::<usize>().ok()).map_or(vi, |t| t - 1);
                        *remap.entry((vi, ti)).or_insert_with(|| {
                            verts.push(v[vi]);
                            uvs.push(vt[ti]);
                            (verts.len() - 1) as u32
                        })
                    })
                    .collect();
                for k in 1..ids.len() - 1 {
                    tris.push([ids[0], ids[k], ids[k + 1]]);
                }
            }
            _ => {}
        }
    }
    let img = image::open(dir.join(format!("{stem}.png"))).unwrap().to_rgba8();
    let tex = Texture2D::new(img.width() as usize, img.height() as usize, img.pixels().map(|p| Color32::from_rgb(p[0], p[1], p[2])).collect());
    let n = tris.len();
    let mut m = Mesh3D::from_parts(
        name.to_string(),
        verts,
        uvs,
        tris,
        vec![0; n],
        Vec::new(),
        Some(tex),
        "Sample atlas 1024x1024".into(),
        1,
        (n / 124).max(1),
        "LOD0".into(),
    );
    m.auto_spin = false;
    m
}

fn load_texture(path: &Path, stem: &str) -> DecodedTexture {
    let img = image::open(path).unwrap().to_rgba8();
    DecodedTexture {
        name: stem.into(),
        w: img.width() as usize,
        h: img.height() as usize,
        mips: 11,
        dxgi: 99,
        fmt_name: "BC7_UNORM_SRGB",
        pixels: img.pixels().map(|p| Color32::from_rgb(p[0], p[1], p[2])).collect(),
        raw_dds_payload: Vec::new(),
        full_size: None,
        reduced_note: None,
    }
}

/// A macOS-style arrow pointer, drawn at `PPP` scale.
fn make_cursor() -> image::RgbaImage {
    let poly: [(f32, f32); 7] = [(0.0, 0.0), (0.0, 16.5), (4.2, 12.6), (7.0, 18.8), (9.6, 17.7), (6.9, 11.7), (12.2, 11.7)];
    let s = PPP * 1.25;
    let (w, h) = ((17.0 * s) as u32, (24.0 * s) as u32);
    let inside = |x: f32, y: f32, grow: f32| -> bool {
        let test = |px: f32, py: f32| {
            let mut c = false;
            let n = poly.len();
            for i in 0..n {
                let (xi, yi) = poly[i];
                let (xj, yj) = poly[(i + n - 1) % n];
                if (yi > py) != (yj > py) && px < (xj - xi) * (py - yi) / (yj - yi) + xi {
                    c = !c;
                }
            }
            c
        };
        if grow == 0.0 {
            return test(x, y);
        }
        test(x, y)
            || (0..12).any(|k| {
                let a = k as f32 * std::f32::consts::TAU / 12.0;
                test(x + a.cos() * grow, y + a.sin() * grow)
            })
    };
    let mut img = image::RgbaImage::new(w, h);
    let ss = 4;
    for py in 0..h {
        for px in 0..w {
            let (mut white, mut black, mut shadow) = (0u32, 0u32, 0u32);
            for sy in 0..ss {
                for sx in 0..ss {
                    let x = (px as f32 + (sx as f32 + 0.5) / ss as f32) / s - 1.2;
                    let y = (py as f32 + (sy as f32 + 0.5) / ss as f32) / s - 1.2;
                    if inside(x, y, 0.0) {
                        black += 1;
                    } else if inside(x, y, 1.15) {
                        white += 1;
                    } else if inside(x - 0.6, y - 1.0, 1.6) {
                        shadow += 1;
                    }
                }
            }
            let n = (ss * ss) as f32;
            let (bw, ww, sw) = (black as f32 / n, white as f32 / n, shadow as f32 / n * 0.3);
            let a = (bw + ww + sw).min(1.0);
            if a > 0.0 {
                let v = (ww * 255.0) / (bw + ww + sw).max(1e-6);
                img.put_pixel(px, py, image::Rgba([v as u8, v as u8, v as u8, (a * 255.0) as u8]));
            }
        }
    }
    img
}

fn draw_cursor(img: &mut image::RgbaImage, cur: &image::RgbaImage, at: egui::Pos2) {
    let ox = (at.x * PPP) as i64 - (1.2 * PPP * 1.25) as i64;
    let oy = (at.y * PPP) as i64 - (1.2 * PPP * 1.25) as i64;
    for (x, y, p) in cur.enumerate_pixels() {
        let (dx, dy) = (ox + x as i64, oy + y as i64);
        if p[3] == 0 || dx < 0 || dy < 0 || dx >= img.width() as i64 || dy >= img.height() as i64 {
            continue;
        }
        let d = img.get_pixel_mut(dx as u32, dy as u32);
        let a = p[3] as f32 / 255.0;
        for c in 0..3 {
            d[c] = (p[c] as f32 * a + d[c] as f32 * (1.0 - a)) as u8;
        }
    }
}

/// Fictional archive listing. Rows with a sample open it; the rest only fill the list.
fn demo_entries(root: &Path) -> (Vec<RpfEntry>, HashMap<usize, Sample>) {
    let mut entries = Vec::new();
    let mut samples = HashMap::new();
    let mut push = |rpf: &str, name: String, kind: &'static str, size: u64, sample: Option<Sample>| {
        if let Some(s) = sample {
            samples.insert(entries.len(), s);
        }
        entries.push(RpfEntry {
            source_rpf: root.join(rpf),
            rpf_name: rpf.into(),
            name,
            kind,
            offset: entries.len() as u64 * 0x1000,
            comp_size: size,
            raw_size: size,
            tracks: 0,
            chunks: Vec::new(),
        });
    };
    // vehicles: one real sample, plus invented names
    push("sunset_vehicles.rpf", "sunset_gt.#ft".into(), "VEH", 2_312_448, Some(Sample::Model("sunset_gt")));
    for (i, n) in [
        "coastline_cruiser", "harbor_taxi", "dune_hopper", "palmetto_van", "marina_pickup", "neon_roadster",
        "flamingo_scooter", "pier_tram", "boardwalk_bike", "seaspray_wagon", "lagoon_jeep", "mango_hatch",
        "breakwater_truck", "riptide_coupe", "tidepool_buggy", "sandpiper_mini", "starlight_limo", "gullwing_gt",
    ]
    .iter()
    .enumerate()
    {
        push("sunset_vehicles.rpf", format!("{n}.#ft"), "VEH", 900_000 + i as u64 * 73_421, None);
    }
    // world + props
    push("sunset_coast.rpf", "prop_harbor_lighthouse.#dr".into(), "MODEL", 1_184_256, Some(Sample::Model("harbor_lighthouse")));
    push("sunset_coast.rpf", "prop_palm_tall.#dr".into(), "MODEL", 764_928, Some(Sample::Model("palm_tall")));
    push("sunset_coast.rpf", "maptile_coast_block_01.#dr".into(), "MODEL", 421_888, Some(Sample::Model("city_block")));
    let props = [
        "beach_chair", "surfboard", "parasol", "lifeguard_tower", "pier_lamp", "neon_arrow", "vending_kiosk", "palm_short",
        "bench_wood", "trash_bin", "bike_rack", "hydrant", "mailbox", "bollard", "buoy", "crate_fish", "rope_coil",
        "deck_chair", "cooler_box", "ice_cream_cart", "sign_motel", "sign_diner", "street_light", "traffic_cone",
    ];
    for i in 0..360u64 {
        let p = props[i as usize % props.len()];
        push("sunset_coast.rpf", format!("prop_{p}_{:02}.#dr", i / props.len() as u64 + 1), "MODEL", 12_000 + (i * 7_919) % 380_000, None);
    }
    for i in 0..220u64 {
        push("sunset_coast.rpf", format!("maptile_coast_{:03}.#dr", i + 2), "MODEL", 60_000 + (i * 15_131) % 900_000, None);
    }
    for i in 0..140u64 {
        push("sunset_coast.rpf", format!("nav_{:03}_{:03}.ynv", i / 12, i % 12), "NAVM", 30_000 + (i * 3_571) % 90_000, None);
    }
    // textures
    for (stem, kb) in [("neon_motel_sign", 1024u64), ("sunset_coast_poster", 1024), ("gt_livery_decals", 1024), ("coast_road", 1024)] {
        push("coast_textures.ttpf", format!("tex_art_{stem}_1024x1024_BC7_UNORM_SRGB.ttpf"), "TTPF", kb * 1024 + 344, Some(Sample::Texture(stem)));
    }
    let fmts = ["BC7_UNORM_SRGB", "BC1_UNORM_SRGB", "BC5_UNORM", "BC3_UNORM_SRGB", "BC4_UNORM"];
    for i in 0..900u64 {
        let side = [256u64, 512, 1024, 2048][(i % 4) as usize];
        push("coast_textures.ttpf", format!("tex_{:05}_{side}x{side}_{}.ttpf", i + 5, fmts[(i % 5) as usize]), "TTPF", side * side / 2, None);
    }
    // audio, video, data
    for i in 0..180u64 {
        push("coast_audio.rpf", format!("sound_{:04}_{}st.awc", i + 1, 1 + (i * 7) % 24), "AWC", 180_000 + (i * 21_377) % 2_400_000, None);
    }
    for i in 0..24u64 {
        let (w, h) = [(1280u64, 720u64), (1920, 1080), (720, 1280)][(i % 3) as usize];
        push("coast_movies.rpf", format!("video_{:03}_{w}x{h}_{}f.bk2", i + 1, 120 + i * 37), "BK2", 4_000_000 + i * 913_337, None);
    }
    push("coast_data.rpf", "sunset_gt_handling.xml".into(), "XML", 1_412, Some(Sample::Text("sunset_gt_handling.xml")));
    for (i, n) in ["weather_profiles", "radio_stations", "shop_inventory", "traffic_density", "marina_berths"].iter().enumerate() {
        push("coast_data.rpf", format!("{n}.xml"), "XML", 2_000 + i as u64 * 977, None);
    }
    push("coast_ui.rpf", "demo_strings.gxt".into(), "GXT", 3_208, Some(Sample::Text("demo_strings.txt")));
    for i in 0..40u64 {
        push("coast_ui.rpf", format!("{:04}_ui.rbf", i + 1), "RBF0", 4_000 + i * 311, None);
    }
    (entries, samples)
}

