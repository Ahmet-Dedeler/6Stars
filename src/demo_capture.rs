impl<'a> Rec<'a> {
    fn click_label_contains(&mut self, label: &str, secs: f32) {
        let p = self.rect_of(label, true).unwrap_or_else(|| panic!("no widget containing {label:?}")).center();
        self.move_to(p, secs);
        self.hold(0.1);
        self.click();
    }

    /// Drags with the primary button from the cursor's position by `delta` points.
    fn drag(&mut self, delta: egui::Vec2, secs: f32) {
        self.button(true);
        self.frame();
        let to = self.cursor + delta;
        self.move_to(to, secs);
        self.button(false);
        self.frame();
    }
}
